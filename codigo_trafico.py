# Asignar cada tram al distrito más cercano (distancia euclídea)
def distrito_mas_cercano(row):
    dists= np.sqrt(
        (distritos["lat_dist"] - row["lat"]) ** 2 +
        (distritos["lon_dist"] - row["lon"]) ** 2
    )
    idx = dists.idxmin()
    return distritos.loc[idx, "Codi_districte"]

