def procesar_csv_trafico_distrito(filepath, df_tram_coords):
    chunks_agregados= []
    for chunk in pd.read_csv(filepath, chunksize=200_000, dtype={"data": str}):
        # Unir con distrito
        chunk= chunk.merge(df_tram_coords[["Tram", "Codi_districte"]],
                           left_on="idTram", right_on="Tram", how="left")
        chunk= chunk.dropna(subset=["Codi_districte"])
        chunk["Codi_districte"]= chunk["Codi_districte"].astype(int)

        # Parsear timestamp
        chunk["datetime"]        = pd.to_datetime(chunk["data"], format="%Y%m%d%H%M%S", errors="coerce")
        chunk["fecha"]           = chunk["datetime"].dt.date
        chunk["Descripcio_torn"] = chunk["datetime"].dt.hour.apply(timestamp_to_torn)

        # Agregar por distrito + fecha + turno
        agg= (
            chunk.groupby(["Codi_districte", "fecha", "Descripcio_torn"])["estatActual"]
            .agg(lambda x: (x >= 2).mean())
            .reset_index()
            .rename(columns={"estatActual": "pct_congestion"})
        )
        chunks_agregados.append(agg)

    df= (
        pd.concat(chunks_agregados)
        .groupby(["Codi_districte", "fecha", "Descripcio_torn"])["pct_congestion"]
        .mean()
        .reset_index()
    )
    df["fecha"]= pd.to_datetime(df["fecha"])
    return df
